export function translate(lang: Lang, key: Key): string {
  if (lang === "ru") return ru[key];
  return lang === "uz_cyrl" ? latinToCyrillic(uz[key]) : uz[key];
}

export function statusLabel(lang: Lang, status: string): string {
  const s = STATUS[status];
  if (!s) return status;
  if (lang === "ru") return s.ru;
  return lang === "uz_cyrl" ? latinToCyrillic(s.uz) : s.uz;
}

export function formatMoney(value: string | number | null | undefined, lang: Lang): string {
  if (value === null || value === undefined || value === "") return "";
  const n = Math.round(Number(value));
  const s = n.toLocaleString("ru-RU").replace(/ /g, " ");
  return `${s} ${translate(lang, "sum")}`;
}
