export type Brand = { slug: string; name: string };
export type Card = {
  id: number;
  slug: string;
  name: string;
  category_slug: string;
  variant_id: number;
  brand: Brand | null;
  price: string;
  old_price: string | null;
  discount_percent: number;
  image: string;
  rating_avg: string;
  rating_count: number;
  stock_status: "in_stock" | "low" | "out_of_stock";
  is_bulky: boolean;
};
export type Page<T> = { count: number; next: string | null; previous: string | null; results: T[] };
export type CategoryNode = { id: number; slug: string; name: string; icon: string; children: CategoryNode[] };
export type Variant = {
  id: number;
  sku: string;
  name_suffix: string;
  price: string;
  old_price: string | null;
  discount_percent: number;
  stock_status: Card["stock_status"];
  options: Record<string, { name: string; value: string; option: string | null }>;
};
export type ProductDetail = Card & {
  description: string;
  model_code: string;
  warranty_months: number;
  category: { id: number; slug: string; name: string }[];
  images: { id: number; url: string }[];
  variants: Variant[];
  attributes: { group: string; items: { code: string; name: string; value: string }[] }[];
};
export type Facets = {
  brands: { slug: string; name: string; count: number }[];
  price: { min: string | null; max: string | null };
  attributes: {
    code: string;
    name: string;
    type: "enum" | "number" | "bool";
    unit: string;
    options?: { code: string; name: string; count: number }[];
    min?: string;
    max?: string;
    count_true?: number;
  }[];
};
export type CartLine = {
  id: number;
  variant_id: number;
  sku: string;
  product: { id: number; slug: string; name: string; is_bulky: boolean; category_slug: string };
  name_suffix: string;
  image: string;
  qty: number;
  unit_price: string;
  old_price: string | null;
  line_total: string;
  stock_status: Card["stock_status"];
  max_qty: number;
  problem: null | "unavailable" | "not_enough_stock";
};
export type Cart = {
  guest_token: string | null;
  items: CartLine[];
  items_count: number;
  subtotal: string;
  total_weight_kg: string;
  has_bulky: boolean;
  can_checkout: boolean;
};
export type Address = {
  id: number;
  label: string;
  district: number;
  settlement: string;
  street: string;
  house: string;
  apartment: string;
  entrance: string;
  floor: number | null;
  elevator: "none" | "passenger" | "freight";
  landmark: string;
  recipient_name: string;
  recipient_phone: string;
  is_default: boolean;
};
export type Quote = {
  quote_id: string;
  provider: string;
  delivery_price: string;
  lifting: { available: boolean; price: string | null };
  eta_days_min: number;
  eta_days_max: number;
  expires_at: string;
};
export type PaymentOption = { code: string; available: boolean; required_prepayment: string; note: string };
export type Summary = {
  subtotal: string;
  delivery_fee: string;
  lifting_fee: string;
  total: string;
  payment_methods: PaymentOption[];
};
export type OrderItem = { id: number; sku: string; name: string; variant_name: string; qty: number; unit_price: string; line_total: string };
export type Order = {
  number: string;
  status: string;
  payment_method: string;
  payment_status: string;
  subtotal: string;
  delivery_fee: string;
  lifting_fee: string;
  total: string;
  required_prepayment: string;
  paid_amount: string;
  cod_amount: string;
  amount_to_pay_online: string;
  payment_deadline: string | null;
  address_snapshot: Record<string, any>;
  recipient_name: string;
  recipient_phone: string;
  delivery_eta_min: number;
  delivery_eta_max: number;
  can_cancel: boolean;
  items: OrderItem[];
  history: { to_status: string; created_at: string; note: string }[];
  created_at: string;
};
export type OrderListItem = Pick<Order, "number" | "status" | "payment_method" | "total" | "created_at"> & { items_count: number };
